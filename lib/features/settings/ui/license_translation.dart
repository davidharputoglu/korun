String? indicativeLicenseTranslation(String source, String languageCode) {
  final translation = _translations[languageCode];
  if (translation == null) return null;
  final normalized = source.toLowerCase();
  if (normalized.contains(
    'permission is hereby granted, free of charge, to any person obtaining a copy',
  )) {
    final copyright = source
        .split('\n')
        .where((line) => line.trimLeft().toLowerCase().startsWith('copyright'))
        .join('\n');
    return '${copyright.isEmpty ? '' : '$copyright\n\n'}${translation.mit}';
  }
  if (normalized.contains('redistribution and use in source and binary forms') &&
      (normalized.contains('neither the name') ||
          normalized.contains('endorse or promote'))) {
    return translation.bsd3;
  }
  return null;
}

